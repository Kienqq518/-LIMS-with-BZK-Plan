import { chromium } from 'playwright';
import { BASE } from './_env.mjs';
const out=[],err=[];
const b=await chromium.launch({channel:'chrome'});
const p=await b.newPage({viewport:{width:1920,height:1080}});
p.on('pageerror',e=>err.push('pageerror: '+e.message));
p.on('console',m=>{if(m.type()==='error'&&!/favicon/.test(m.text()))err.push('console: '+m.text().slice(0,160));});
await p.goto(BASE+'/twin/future-lab/twin-scene-v2.html',{waitUntil:'load'});
await p.waitForTimeout(15000);
const f=p.frames().find(x=>/tour-space/.test(x.url()));
const T=(k,v,e)=>out.push((String(v)===String(e)?'✅':'❌')+` ${k}: ${v} (期望 ${e})`);
T('低配按钮已移除', await p.locator('#lowBtn').count(), 0);
T('顶栏无「低配」文字', (await p.locator('.acts').innerText()).includes('低配'), false);
T('全屏按钮存在', await p.locator('#fsBtn').count(), 1);
T('全屏按钮带图标', await p.locator('#fsBtn svg').count(), 1);
T('初始文案', (await p.locator('#fsBtn .fs-t').innerText()), '全屏');
await p.click('#fsBtn'); await p.waitForTimeout(1200);
const fs1=await p.evaluate(()=>!!(document.fullscreenElement||document.webkitFullscreenElement));
T('点一次进入全屏', fs1, true);
T('全屏后文案', (await p.locator('#fsBtn .fs-t').innerText()), '退出全屏');
T('aria-pressed', await p.getAttribute('#fsBtn','aria-pressed'), 'true');
T('body[data-full]', await p.evaluate(()=>document.body.dataset.full), '1');
const lay=await p.evaluate(()=>{const r=document.querySelector('.rail').getBoundingClientRect();const s=document.querySelector('.stream').getBoundingClientRect();return {rail:Math.round(r.x),streamRight:Math.round(innerWidth-s.right)};});
out.push(((lay.rail>=0&&lay.streamRight>=0&&lay.streamRight<40)?'✅':'❌')+' 全屏下浮层仍贴边: '+JSON.stringify(lay));
await p.screenshot({path:'/tmp/twin-qa/fs-on.png'});
await p.click('#fsBtn'); await p.waitForTimeout(1000);
T('再点退出全屏', await p.evaluate(()=>!!(document.fullscreenElement||document.webkitFullscreenElement)), false);
await p.keyboard.press('f'); await p.waitForTimeout(1200);
T('快捷键 F 进入全屏', await p.evaluate(()=>!!(document.fullscreenElement||document.webkitFullscreenElement)), true);
await p.keyboard.press('f'); await p.waitForTimeout(900);
T('快捷键 F 退出', await p.evaluate(()=>!!(document.fullscreenElement||document.webkitFullscreenElement)), false);
// 低配能力仍在（交付参数）
const p2=await b.newPage({viewport:{width:1920,height:1080}});
await p2.goto(BASE+'/twin/future-lab/twin-scene-v2.html?mode=S1&period=day&layers=path,labels&quality=low',{waitUntil:'load'});
await p2.waitForTimeout(14000);
const f2=p2.frames().find(x=>/tour-space/.test(x.url()));
const q=await f2.evaluate(()=>document.getElementById('twin-v2-bridge')?.dataset.quality);
out.push((q==='low'?'✅':'❌')+' 低配能力保留为交付参数 ?quality=low（场景侧 quality='+q+'）');
console.log(out.join('\n')); console.log('errors('+err.length+'):\n'+err.slice(0,5).join('\n'));
await b.close();
